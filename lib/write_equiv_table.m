function write_equiv_table(eq, jac, tex_file)
% WRITE_EQUIV_TABLE  Rows of the Online IV table (contents of a tabular).
%   Panel A: alternative gamQ that reproduces the baseline IS resp. real
%   wage slope (aggregate) at nuD = 1, 2, 3 and Gamma_Q closest to baseline;
%   CU, PE, LW report how the non-targeted gap coefficients move.
%   Panel B: Phillips curve (gamQ pinned; nuD solving AS_ag), and the local
%   Jacobian singular values.
if nargin < 3, tex_file = nksam_path('tables', 'tab_param_equiv.tex'); end
b = eq.baseline;
[~, iS] = min(abs(eq.AD.subQ_grid - b.subQ));      % Gamma_Q closest to baseline
L = {};
L{end+1} = sprintf('%% generated by scripts/online_IV_equivalence.m -- do not edit by hand (%s)', datestr(now,'yyyy-mm-dd HH:MM'));
L{end+1} = sprintf('\\multicolumn{8}{l}{\\textit{Panel A: match one slope, solve for $\\gamma_Q$ ($\\Gamma_Q=%.2f$)}}\\\\', eq.AD.subQ_grid(iS));
L{end+1} = '\hline';
L{end+1} = 'Matched slope & $\nu_D$ & $\gamma_Q$ & CU & PE & LW & IS & RW \\';
L{end+1} = '\hline';
L{end+1} = sprintf('Baseline & $%.1f$ & $%.2f$ & $%.2f$ & $%.2f$ & $%.2f$ & $%.2f$ & $%.2f$ \\\\', b.nuD, b.gamQ, b.CU_ag, b.PE_ag, b.LW_ag, b.AD_ag, b.WG_ag);
names = {'AD','IS slope'; 'WG','Real wage slope'};
for e = 1:2
    ex = eq.(names{e,1});
    for nu = [1 2 3]
        [~, iT] = min(abs(ex.nuD_grid - nu));
        if isnan(ex.gamQ_used(iS,iT)), continue; end
        c = ex.coef;
        if nu == 1, lab = names{e,2}; else, lab = ' '; end
        L{end+1} = sprintf('%s & $%.1f$ & $%.2f$ & $%.2f$ & $%.2f$ & $%.2f$ & $%.2f$ & $%.2f$ \\\\', lab, ex.nuD_grid(iT), ...
            ex.gamQ_used(iS,iT), c.CU_ag(iS,iT), c.PE_ag(iS,iT), c.LW_ag(iS,iT), c.AD_ag(iS,iT), c.WG_ag(iS,iT)); %#ok<AGROW>
    end
end
[~, iA] = min(abs(eq.AS.subQ_grid - b.subQ));
if ~isnan(eq.AS.nuD_used(iA))
    c = eq.AS.coef;
    L{end+1} = sprintf('Phillips slope ($\\gamma_Q$ pinned) & $%.1f$ & $%.2f$ & $%.2f$ & $%.2f$ & $%.2f$ & $%.2f$ & $%.2f$ \\\\', ...
        eq.AS.nuD_used(iA), eq.AS.gamQ_fixed, c.CU_ag(iA), c.PE_ag(iA), c.LW_ag(iA), c.AD_ag(iA), c.WG_ag(iA)); %#ok<AGROW>
end
L{end+1} = '\hline';
L{end+1} = '\multicolumn{8}{l}{\textit{Panel B: local identification, singular values of the slope Jacobian}}\\';
L{end+1} = '\hline';
L{end+1} = ' & $(\gamma_Q,\Gamma_Q)$ & $\sigma_1$ & $\sigma_2$ & $\sigma_3$ & $\sigma_3/\sigma_1$ & $\Gamma_Q$ share & \\';
for r = 1:size(jac.pts,1)
    w = jac.weak(r,:).^2;
    L{end+1} = sprintf('All six slopes & $(%g,%g)$ & $%.2f$ & $%.2f$ & $%.3f$ & $%.3f$ & $%.2f$ & \\\\', ...
        jac.pts(r,1), round(jac.pts(r,2),2)+0, jac.sv(r,:), jac.sv(r,3)/jac.sv(r,1), w(2)/sum(w)); %#ok<AGROW>
end
d = fileparts(tex_file); if ~isempty(d) && ~exist(d,'dir'), mkdir(d); end
fid = fopen(tex_file,'w'); fprintf(fid,'%s\n',L{:}); fclose(fid);
fprintf('Wrote %s\n', tex_file);
end
