function cleanup_dynare_output(enabled)
% CLEANUP_DYNARE_OUTPUT  Delete Dynare's regenerable build and simulation output.
%
%   cleanup_dynare_output()         use the default below (or the override)
%   cleanup_dynare_output(true)     force deletion
%   cleanup_dynare_output(false)    keep everything (no-op)
%
%   Called at the end of every script that runs Dynare. Deletes, anywhere
%   under the codebase:
%     - every folder named nk_time/: nk_time/Output/nk_time_simul (~0.9 GB,
%       the simul_replic dump that stoch_simul writes to the current folder
%       and that nothing reads back) and model/nk_time/ (preprocessor output)
%     - model/+nk_time/ and model/nk_time.log (preprocessor output)
%   All of this is regenerated by the `dynare nk_time.dyn` call in
%   lib/setup_dynare.m at the start of every Dynare script, so deleting it
%   never affects results. Results and caches are NOT touched.
%
%   SETTING THE OPTION
%     Default: DEFAULT_CLEANUP below.
%     Override without editing this file (survives the `clear all` in the
%     setup scripts); run_all sets it from OPT.cleanup_dynare (run_all_options.m):
%       setenv('NKSAM_CLEANUP_DYNARE', '0');   % keep Dynare output
%       setenv('NKSAM_CLEANUP_DYNARE', '1');   % delete it
%       setenv('NKSAM_CLEANUP_DYNARE', '');    % back to the default
%     Precedence: explicit argument > environment variable > default.
%
%   Do not call this in the middle of a Dynare run: the M_/oo_ solution in
%   memory survives, but dynare_scenario needs the +nk_time package files
%   until the driver is finished.

DEFAULT_CLEANUP = true;

if nargin < 1 || isempty(enabled)
    env = strtrim(getenv('NKSAM_CLEANUP_DYNARE'));
    if isempty(env)
        enabled = DEFAULT_CLEANUP;
    else
        enabled = ~any(strcmpi(env, {'0', 'false', 'off', 'no'}));
    end
end
if ~enabled
    fprintf('cleanup_dynare_output: skipped (Dynare output kept).\n');
    return;
end

repo_root = nksam_path('root');
model_dir = nksam_path('model');

% Collect targets
targets = {};
d = dir(fullfile(repo_root, '**'));
d = d([d.isdir] & strcmp({d.name}, 'nk_time'));
for k = 1:numel(d)
    targets{end+1} = fullfile(d(k).folder, d(k).name); %#ok<AGROW>
end
targets{end+1} = fullfile(model_dir, '+nk_time');
targets{end+1} = fullfile(model_dir, 'nk_time.log');
targets = unique(targets);

% Delete
n_del = 0; bytes = 0;
for k = 1:numel(targets)
    p = targets{k};
    if isfolder(p)
        bytes = bytes + folder_bytes(p);
        [ok, msg] = rmdir(p, 's');
    elseif isfile(p)
        f = dir(p); bytes = bytes + f.bytes;
        delete(p); ok = ~isfile(p); msg = '';
    else
        continue;
    end
    if ok
        n_del = n_del + 1;
    else
        warning('cleanup_dynare_output:failed', 'could not delete %s (%s)', p, msg);
    end
end
rehash;
fprintf('cleanup_dynare_output: deleted %d Dynare output item(s), %.2f GB freed.\n', ...
    n_del, bytes / 1024^3);
end

function b = folder_bytes(p)
f = dir(fullfile(p, '**', '*'));
b = sum([f(~[f.isdir]).bytes]);
end
