function robust_write_summary(checks, base, outs, S, run_ok, g)
% ROBUST_WRITE_SUMMARY  Numbers for tab:robust_regimes and tab:robust_magnitudes (Online Appendix VI).
%
%   2026-10-11 restructure: one table per robustness question. Replaces tab_robust_panelA.tex
%   and tab_robust_full.tex (no longer written); the search-effort statistics (corr(lw,Y),
%   sd(cu)/sd(Y)) are no longer tabulated, only logged in the .txt and .mat.
%
%   Writes
%     results/tables/tab_robust_regimes.tex     rows of tab:robust_regimes (Table VI.2, landscape),
%                                        21 columns: 2 labels | thresholds omega*_q, omega*_Xi |
%                                        omega_shock for g.shocks | NK-SaM/benchmark impact Y |
%                                        impact pi | Y summed over the horizon (4 spacers)
%     results/tables/tab_robust_magnitudes.tex  rows of tab:robust_magnitudes (Table VI.3), 13 columns:
%                                        2 labels | impact Y and pi relative to baseline NK-SaM for
%                                        g.shocks | channel slopes relative to baseline (1 spacer)
%     results/txt/robustness_summary.txt full log: levels, ratios, steady
%                                        states and solved parameters
%     results/mat/robustness_summary.mat the table numbers per variant
%                                        (rows, base_row)
%
%   tab_robust_magnitudes (fidA): impact responses (period 1) of real GDP and inflation in the
%     NK-SaM model with the change, relative to baseline NK-SaM, for the shocks in g.shocks
%     (main-text order); static channel slopes Theta_Y^q, Theta_Y^Xi relative to baseline
%     (reduced-form model; empty if not nested).
%   tab_robust_regimes (fidB): each omega_shock cell carries the dominant Barro-Grossman quadrant
%     of the shock as a small code (function quads below; 2026-10-11); (i) thresholds omega*_q,
%     omega*_Xi of the variant (reduced-form
%     model, S.thr; empty if not nested); (ii) comovement omega_shock = sum_t u~_t Y~_t /
%     sum_t Y~_t^2 over the IRF horizon (ue_gap in pp, gdp_gap in %; as
%     scripts/main_s5_slope_summary.m), NK-SaM, g.shocks; (iii)-(v) NK-SaM relative to the
%     benchmark WITH THE SAME CHANGE (baseline benchmark if the change does not affect it), for
%     g.dir_shocks: impact real GDP, impact inflation, real GDP summed over the IRF horizon
%     (g.irfperiod quarters).
%   Logged only (.txt and .mat): benchmark omega_shock (om_nk), impact employment ratios
%     (sign reversals), search-effort shock in isolation (corr(lw,Y), corr(cu,Y), sd(cu)/sd(Y)).
%   Failed checks (run_ok(c) = false) get empty cells.

fA = nksam_path('tables', 'tab_robust_magnitudes.tex');   % Table VI.3 (2026-10-11)
fB = nksam_path('tables', 'tab_robust_regimes.tex');      % Table VI.2 (2026-10-11)
fT = nksam_path('txt', 'robustness_summary.txt');
ensure_dir(fA); ensure_dir(fT);
fidA = fopen(fA, 'w'); fidB = fopen(fB, 'w'); fidT = fopen(fT, 'w');
if any([fidA fidB fidT] < 0), error('robust_write_summary: cannot open output files.'); end
cleanupObj = onCleanup(@() cellfun(@fclose, {fidA, fidB, fidT})); %#ok<NASGU>

hdr = '%% generated by scripts/online_VI_robustness.m -- do not edit by hand (%s)\n';
fprintf(fidA, hdr, datestr(now, 'yyyy-mm-dd HH:MM'));
fprintf(fidB, hdr, datestr(now, 'yyyy-mm-dd HH:MM'));

shocks = cellstr(g.shocks);
dsh    = cellstr(g.dir_shocks);
imp    = @(r, sh, v) r.irfs.(sh).(v)(1);
cum    = @(r, sh, v) sum(r.irfs.(sh).(v));          % over the IRF horizon
rat    = @(f, a, b, v) cellfun(@(sh) f(a, sh, v) / f(b, sh, v), dsh);
omg    = @(r, shs) cellfun(@(sh) sum(r.irfs.(sh).ue_gap .* r.irfs.(sh).gdp_gap) / ...
                                 sum(r.irfs.(sh).gdp_gap.^2), shs);

% ------------------------------------------------------------------ baseline
dir_base = cellfun(@(sh) imp(base.sam, sh, 'gdp_obs') / imp(base.nk, sh, 'gdp_obs'), dsh);
fprintf(fidA, 'Baseline & -- %s & & $1.00$ & $1.00$ \\\\\n', repmat(' & $1.00$', 1, 2*numel(shocks)));
fprintf(fidA, '\\hline\n');
dpi_base = rat(imp, base.sam, base.nk, 'piC');
dcum_base = rat(cum, base.sam, base.nk, 'gdp_obs');
dn_base  = rat(imp, base.sam, base.nk, 'n');
om_sam_base = omg(base.sam, shocks);
[qd_base, qw_base] = quads(base.sam, shocks);
% tab_robust_regimes: thresholds | omega_shock with quadrant code | Y impact | pi impact | Y summed over the horizon
fprintf(fidB, 'Baseline & -- %s &%s &%s &%s &%s \\\\\n', num_cells(S.thr_base), ...
        om_cells(om_sam_base, qd_base), num_cells(dir_base), num_cells(dpi_base), num_cells(dcum_base));
fprintf(fidB, '\\hline\n');
om_nk_base  = omg(base.nk,  dsh);
base_row = struct('D', dir_base, 'Dpi', dpi_base, 'Dcum', dcum_base, 'Dn', dn_base, ...
                  'om_sam', om_sam_base, 'om_nk', om_nk_base, 'thr', S.thr_base, ...
                  'quad', {qd_base}, 'quad_share', qw_base, ...
                  'corr_lw_y', base.iso.corr_lw_y, 'relstd_cu_y', base.iso.relstd_cu_y);
rows = {};   % one struct per variant -> robustness_summary.mat

% ------------------------------------------------------------------ log head
fprintf(fidT, 'ROBUSTNESS SUMMARY (Online Appendix VI) -- %s\n\n', datestr(now));
fprintf(fidT, 'Baseline impact responses (percent, 1 s.d. shocks)\n');
fprintf(fidT, '%-10s %10s %10s %10s %10s\n', 'shock', 'Y NK-SaM', 'pi NK-SaM', 'Y bench', 'pi bench');
for ii = 1:numel(shocks)
    sh = shocks{ii};
    fprintf(fidT, '%-10s %10.4f %10.4f %10.4f %10.4f\n', sh, imp(base.sam, sh, 'gdp_obs'), ...
        imp(base.sam, sh, 'piC'), imp(base.nk, sh, 'gdp_obs'), imp(base.nk, sh, 'piC'));
end
fprintf(fidT, 'Static slopes (reduced form): Theta_Y^q = %.4f, Theta_Y^Xi = %.4f\n', S.base);
fprintf(fidT, 'Thresholds (reduced form): omega*_q = %.4f, omega*_Xi = %.4f\n', S.thr_base);
fprintf(fidT, 'Dominant quadrant NK-SaM (%s): %s\n', strjoin(shocks, ', '), quad_str(qd_base, qw_base));
fprintf(fidT, 'omega_shock NK-SaM (%s): %s | benchmark (%s): %s\n', strjoin(shocks, ', '), ...
        sprintf(' %.3f', om_sam_base), strjoin(dsh, ', '), sprintf(' %.3f', om_nk_base));
fprintf(fidT, 'Search-effort shock alone: corr(lw,Y) = %.3f, corr(cu,Y) = %.3f, sd(cu)/sd(Y) = %.3f\n\n', ...
        base.iso.corr_lw_y, base.iso.corr_cu_y, base.iso.relstd_cu_y);
log_mp_wage_util(fidT, 'baseline NK-SaM', base.sam);
log_ss(fidT, 'baseline NK-SaM', base.sam);
log_ss(fidT, 'baseline benchmark', base.nk);

% ------------------------------------------------------------------ checks
% Rows in display order (checks(c).table_order; the literature combinations follow check 7),
% with one header row per part (checks(c).part: A goods market SaM, B Phillips-curve calibration,
% C shared model structure; 2026-10-09). Table widths (2026-10-11): tab_robust_magnitudes 13 columns,
% tab_robust_regimes 21 columns (15 numbers, omega cells with quadrant codes, + 4 spacers + 2 labels).
[~, ord] = sort([checks.table_order]);
part_prev = '';
for c = ord
    chk = checks(c);
    if ~strcmp(chk.part, part_prev)
        ttl = part_title(chk.part);
        if ~isempty(part_prev)
            fprintf(fidA, '\\hline\n'); fprintf(fidB, '\\hline\n');
        end
        fprintf(fidA, '\\multicolumn{13}{l}{\\textit{%s}} \\\\\n', ttl);
        fprintf(fidB, '\\multicolumn{21}{l}{\\textit{%s}} \\\\\n', ttl);
        part_prev = chk.part;
    end
    if isnan(chk.num), cnum = '--'; else, cnum = sprintf('%d', chk.num); end
    fprintf(fidT, '\n==== %s. %s (%s) ====\n', cnum, chk.title, chk.tag);
    for k = 1:numel(chk.ext)
        e = chk.ext(k);
        A = NaN(1, 2*numel(shocks)); D = NaN(1, numel(dsh));
        Dpi = D; Dcum = D; Dn = D;
        om_s = NaN(1, numel(shocks)); om_n = NaN(1, numel(dsh));
        qd = repmat({''}, 1, numel(shocks)); qw = NaN(1, numel(shocks));
        iso = struct('corr_lw_y', NaN, 'corr_cu_y', NaN, 'relstd_cu_y', NaN);
        var_ok = run_ok(c) && ~isempty(outs{c}.sam{k});
        if var_ok
            o = outs{c};
            for ii = 1:numel(shocks)
                sh = shocks{ii};
                A(2*ii-1) = imp(o.sam{k}, sh, 'gdp_obs') / imp(base.sam, sh, 'gdp_obs');
                A(2*ii)   = imp(o.sam{k}, sh, 'piC')     / imp(base.sam, sh, 'piC');
            end
            if chk.bench_changes, nk_ref = o.nk{k}; else, nk_ref = base.nk; end
            D    = cellfun(@(sh) imp(o.sam{k}, sh, 'gdp_obs') / imp(nk_ref, sh, 'gdp_obs'), dsh);
            Dpi  = rat(imp, o.sam{k}, nk_ref, 'piC');
            Dcum = rat(cum, o.sam{k}, nk_ref, 'gdp_obs');
            Dn   = rat(imp, o.sam{k}, nk_ref, 'n');
            om_s = omg(o.sam{k}, shocks);
            om_n = omg(nk_ref, dsh);
            [qd, qw] = quads(o.sam{k}, shocks);
            iso = o.iso{k};
        end
        R = S.ratio{c}(k, :);
        Th = S.thr{c}(k, :);

        fprintf(fidA, '%s & %s%s & & %s & %s \\\\\n', e.row, e.change, num_cells(A), num(R(1)), num(R(2)));
        fprintf(fidB, '%s & %s%s &%s &%s &%s &%s \\\\\n', e.row, e.change, num_cells(Th), ...
                om_cells(om_s, qd), num_cells(D), num_cells(Dpi), num_cells(Dcum));
        rows{end+1} = struct('check', c, 'tag', chk.tag, 'title', chk.title, ...
            'k', k, 'nvar', numel(chk.ext), 'leg', e.leg, 'change', e.change, ...
            'ok', var_ok, 'A', A, 'D', D, 'Dpi', Dpi, 'Dcum', Dcum, 'Dn', Dn, 'slopes', R, 'thr', Th, ...
            'om_sam', om_s, 'om_nk', om_n, 'quad', {qd}, 'quad_share', qw, ...
            'corr_lw_y', iso.corr_lw_y, 'relstd_cu_y', iso.relstd_cu_y); %#ok<AGROW>

        fprintf(fidT, '-- %s  [%s]\n', e.change, e.group);
        if ~var_ok, fprintf(fidT, '   FAILED (see robustness_log.txt)\n'); continue; end
        fprintf(fidT, '   Panel A (Y, pi relative to baseline NK-SaM):');
        for ii = 1:numel(shocks)
            fprintf(fidT, '  %s: %.3f / %.3f', shocks{ii}, A(2*ii-1), A(2*ii));
        end
        fprintf(fidT, '\n   NK-SaM / benchmark impact Y:');
        for ii = 1:numel(dsh), fprintf(fidT, '  %s: %.3f', dsh{ii}, D(ii)); end
        fprintf(fidT, '   (baseline:'); fprintf(fidT, ' %.3f', dir_base); fprintf(fidT, ')\n');
        fprintf(fidT, '   NK-SaM / benchmark: impact pi %s | cumulative Y %s | impact N %s\n', ...
                sprintf(' %.3f', Dpi), sprintf(' %.3f', Dcum), sprintf(' %.3f', Dn));
        fprintf(fidT, '   omega_shock NK-SaM:%s | benchmark:%s\n', sprintf(' %.3f', om_s), sprintf(' %.3f', om_n));
        fprintf(fidT, '   static slopes: levels %.4f / %.4f, ratios %.3f / %.3f\n', S.val{c}(k, :), R);
        fprintf(fidT, '   thresholds: omega*_q = %.3f, omega*_Xi = %.3f\n', Th);
        fprintf(fidT, '   dominant quadrant NK-SaM: %s\n', quad_str(qd, qw));
        fprintf(fidT, '   search-effort alone: corr(lw,Y) = %.3f, corr(cu,Y) = %.3f, sd(cu)/sd(Y) = %.3f\n', ...
                iso.corr_lw_y, iso.corr_cu_y, iso.relstd_cu_y);
        log_mp_wage_util(fidT, ['NK-SaM, ' e.leg], outs{c}.sam{k});
        log_ss(fidT, ['NK-SaM, ' e.leg], outs{c}.sam{k});
        if strcmp(chk.tag, 'capital')   % utilization check: fixed vs variable (delF2/delH2)
            log_util(fidT, ['NK-SaM, ' e.leg], outs{c}.sam{k}, shocks);
            if chk.bench_changes, log_util(fidT, ['benchmark, ' e.leg], outs{c}.nk{k}, shocks); end
        end
        if chk.bench_changes, log_ss(fidT, ['benchmark, ' e.leg], outs{c}.nk{k}); end
    end
end
rows    = [rows{:}];
% Online V.4 (sec:emp_checks_add): across the baseline and all variants, correlation of
% sd(cu)/sd(Y) with corr(lw,Y) under the search-effort shock alone
rs = [base_row.relstd_cu_y, rows.relstd_cu_y]; cl = [base_row.corr_lw_y, rows.corr_lw_y];
okv = ~isnan(rs) & ~isnan(cl);
cc = corrcoef(rs(okv), cl(okv));
fprintf(fidT, ['\nSearch-effort shock alone, baseline and all variants (n = %d): sd(cu)/sd(Y) from %.3f to %.3f; ' ...
               'corr(sd(cu)/sd(Y), corr(lw,Y)) = %.3f\n'], sum(okv), min(rs(okv)), max(rs(okv)), cc(1,2));
created = datestr(now, 'yyyy-mm-dd HH:MM'); %#ok<NASGU>
fM = nksam_path('mat', 'robustness_summary.mat');
save(fM, 'rows', 'base_row', 'shocks', 'dsh', 'created');
fprintf('  wrote %s, %s, %s, %s\n', fA, fB, fT, fM);
end

% =========================================================================
function log_mp_wage_util(fid, lbl, r)
% Impact responses of the real wage and capacity utilization to monetary policy
% (OA VI, sec:robust_rigidity, 'The Real Wage as the Link')
if isfield(r.irfs, 'eM') && isfield(r.irfs.eM, 'w_obs') && isfield(r.irfs.eM, 'cu')
    fprintf(fid, '   monetary policy, impact, %s: real wage %.3f %%, capacity utilization %.3f pp\n', ...
            lbl, r.irfs.eM.w_obs(1), r.irfs.eM.cu(1));
end
end

% =========================================================================
function s = part_title(p)
switch p
    case 'A', s = 'Part A: Goods market SaM';
    case 'B', s = 'Part B: Phillips-curve calibration';
    case 'C', s = 'Part C: Shared model structure';
    otherwise, s = p;
end
end

function s = num(x)
if isnan(x), s = ''; return; end
if abs(x) < 0.005, x = 0; end          % no '-0.00' (e.g. omega_shock under flexible wages)
s = sprintf('$%.2f$', x);
end

function [qd, qw] = quads(r, shocks)
% QUADS  Barro-Grossman quadrant in the gap plane (2026-10-11): for each shock, the quadrant of
%   (tightness gap, unemployment gap) in which the IRF spends most of the horizon, each period
%   weighted by |output gap| as in omega_shock. The tightness gap is proportional to the
%   utilization gap cu_gap (sec:phase_diagram). Codes: UC underconsumption (cu<0, u<0), RI
%   repressed inflation (cu>0, u<0), CU classical unemployment (cu>0, u>0), KU Keynesian
%   unemployment (otherwise). '--' if the unemployment gap is identically zero (flexible wages).
lab = {'UC', 'RI', 'KU', 'CU'};
qd = cell(1, numel(shocks)); qw = NaN(1, numel(shocks));
for ii = 1:numel(shocks)
    ir = r.irfs.(shocks{ii});
    q = ir.cu_gap(:); u = ir.ue_gap(:); y = ir.gdp_gap(:);
    if max(abs(u)) < 1e-8, qd{ii} = '--'; continue; end
    w = abs(y) / sum(abs(y));
    k = 3 * ones(size(q));                    % KU
    k(q < 0 & u < 0) = 1; k(q > 0 & u < 0) = 2; k(q > 0 & u > 0) = 4;
    sh = arrayfun(@(j) sum(w(k == j)), 1:4);
    [qw(ii), j] = max(sh); qd{ii} = lab{j};
end
end

function s = om_cells(x, qd)
% omega_shock cells with the quadrant code appended in small type, e.g. '$-5.81$\,{\tiny UC}'.
s = '';
for ii = 1:numel(x)
    c = num(x(ii));
    if ~isempty(c) && ~isempty(qd{ii}), c = [c '\,{\tiny ' qd{ii} '}']; end
    s = [s ' & ' c]; %#ok<AGROW>
end
end

function s = quad_str(qd, qw)
s = '';
for ii = 1:numel(qd)
    if isnan(qw(ii)), s = [s ' ' qd{ii}]; else, s = [s sprintf(' %s(%.0f%%)', qd{ii}, 100*qw(ii))]; end %#ok<AGROW>
end
end

function s = num_cells(x)
s = '';
for ii = 1:numel(x), s = [s ' & ' num(x(ii))]; end %#ok<AGROW>
end

function log_ss(fid, name, r)
fprintf(fid, '   steady state, %s:', name);
f = fieldnames(r.ss);
for ii = 1:numel(f), fprintf(fid, ' %s=%.4g', f{ii}, r.ss.(f{ii})); end
fprintf(fid, '\n   parameters, %s:', name);
f = fieldnames(r.par);
for ii = 1:numel(f), fprintf(fid, ' %s=%.4g', f{ii}, r.par.(f{ii})); end
fprintf(fid, '\n');
if isfield(r.ss, 'dq') && isfield(r.ss, 'd') && r.ss.d > 0
    fprintf(fid, '   shopping time split: dq/d = %.4f, dp/d = %.4f', r.ss.dq/r.ss.d, r.ss.dp/r.ss.d);
    if r.ss.dq <= 0, fprintf(fid, '   *** WARNING: quantity search dq <= 0 ***'); end
    fprintf(fid, '\n');
end
end

function log_util(fid, name, r, shocks)
% Largest absolute IRF (percent) of market (ef) and home (eh) capital
% utilization over all plotted shocks and horizons. With delF2 = delH2 = 1e3
% ("fixed utilization") these should be ~1/3000 of the variable-utilization
% values (delF2 = delH2 = 0.3), since e_hat = (rk_hat - qf_hat + muc_hat)/delF2.
fprintf(fid, '   utilization, %s: max|IRF|', name);
for v = {'ef', 'eh'}
    m = 0;
    for ii = 1:numel(shocks)
        if isfield(r.irfs, shocks{ii}) && isfield(r.irfs.(shocks{ii}), v{1})
            m = max(m, max(abs(r.irfs.(shocks{ii}).(v{1}))));
        end
    end
    fprintf(fid, '  %s = %.3g', v{1}, m);
end
fprintf(fid, '\n');
end
